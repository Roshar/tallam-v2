/** Критерии карт оценки (из tallam_2025_v1) */

export type CriterionOption = { value: number; label: string };
export type CriterionDef = {
  key: string;
  code: string;
  title: string;
  options: CriterionOption[];
  /** HTML/text подсказка по баллам — заполним отдельно */
  hint?: string;
};

export type CriteriaSubsection = {
  id: string;
  title: string;
  items: CriterionDef[];
};

export type CriteriaGroup = {
  id: string;
  title: string;
  maxScoreLabel: string;
  subsections: CriteriaSubsection[];
};

